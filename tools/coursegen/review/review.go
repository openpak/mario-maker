// Package review writes the review folder: one directory per course in the
// game's save-folder layout, a YAML manifest per course, preview images, a
// contact sheet and an HTML index.
package review

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"html"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/openpak/mario-maker/tools/coursegen/gen"
	"github.com/openpak/mario-maker/tools/coursegen/render"
	"github.com/openpak/mario-maker/tools/coursegen/smm1"
	"github.com/openpak/mario-maker/tools/coursegen/validate"
)

// Result is one written course.
type Result struct {
	Meta   *gen.Meta
	Report *validate.Report
	Dir    string
}

func q(s string) string { return strconv.Quote(s) }

func sum(b []byte) string {
	h := sha256.Sum256(b)
	return hex.EncodeToString(h[:])
}

func styleLabel(s smm1.Style) string {
	return map[smm1.Style]string{smm1.SMB1: "SMB1", smm1.SMB3: "SMB3", smm1.SMW: "SMW", smm1.NSMBU: "NSMBU"}[s]
}

// Manifest renders the YAML manifest of one course.
func Manifest(m *gen.Meta, rep *validate.Report, files map[string]string) string {
	var sb strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&sb, f+"\n", a...) }
	list := func(key string, xs []string) {
		if len(xs) == 0 {
			w("%s: []", key)
			return
		}
		w("%s:", key)
		for _, x := range xs {
			w("  - %s", q(x))
		}
	}
	w("# OpenPak starter course. Generated by coursegen; NOT verified in the game.")
	w("id: %d", m.Index)
	w("slug: %s", q(m.Slug))
	w("name: %s", q(m.Name))
	w("maker: %s", q(gen.MakerName))
	w("style: %s", styleLabel(m.Style))
	w("style_code: %s", q(string(m.Style)))
	w("theme: %s", q(m.Theme.String()))
	w("difficulty: %s", q(string(m.Band)))
	list("templates", m.Templates)
	w("length_blocks: %d", rep.Stats.LengthBlks)
	w("goal_block: %d", rep.Stats.GoalBlock)
	w("timer_seconds: %d", m.Timer)
	w("objects: %d", rep.Stats.Objects)
	w("enemies: %d", rep.Stats.Enemies)
	w("coins: %d", rep.Stats.Coins)
	w("widest_gap: %d", rep.Stats.MaxGap)
	w("seed: %d", m.Seed)
	w("description: %s", q(m.Description))
	w("validation:")
	w("  ok: %t", rep.OK())
	w("  reachable_positions: %d", rep.Stats.Reachable)
	w("  positions_that_can_finish: %d", rep.Stats.CanFinish)
	list("  errors", rep.Errors)
	list("  warnings", rep.Warnings)
	w("files:")
	for _, n := range []string{"course_data.cdt", "course_data_sub.cdt", "sound.bwv", "thumbnail0.tnl", "thumbnail1.tnl"} {
		w("  %s: %s", n, q(files[n]))
	}
	w("status:")
	w("  verified_in_game: false")
	w("  play_tested: false")
	w("  keep: null  # set to true or false after play-testing; the best 48 are kept")
	w("  notes: \"\"")
	return sb.String()
}

// Write writes the whole set under dir and returns the per-course results.
func Write(dir string, cs []*smm1.Course, ms []*gen.Meta) ([]Result, error) {
	var res []Result
	var prev, over []render.Item
	for i, c := range cs {
		m := ms[i]
		cdir := filepath.Join(dir, m.Slug)
		if err := os.MkdirAll(cdir, 0o755); err != nil {
			return nil, err
		}
		main, err := c.Marshal()
		if err != nil {
			return nil, err
		}
		sub, err := c.MarshalSub()
		if err != nil {
			return nil, err
		}
		// Validate the bytes that will be written, not the in-memory course.
		rep, err := validate.CheckBytes(main, validate.Options{})
		if err != nil {
			return nil, fmt.Errorf("%s: %w", m.Name, err)
		}
		parsed, _ := smm1.Parse(main)
		ov, pv := render.Overview(parsed), render.Preview(parsed)
		j0, err := render.JPEG(ov, smm1.ThumbMaxJPEG)
		if err != nil {
			return nil, err
		}
		j1, err := render.JPEG(pv, smm1.ThumbMaxJPEG)
		if err != nil {
			return nil, err
		}
		t0, err := smm1.PackThumbnail(j0)
		if err != nil {
			return nil, err
		}
		t1, err := smm1.PackThumbnail(j1)
		if err != nil {
			return nil, err
		}
		pngPrev, _ := render.PNG(pv)
		pngOver, _ := render.PNG(ov)
		files := map[string][]byte{
			"course_data.cdt": main, "course_data_sub.cdt": sub, "sound.bwv": smm1.Sound(),
			"thumbnail0.tnl": t0, "thumbnail1.tnl": t1, "preview.png": pngPrev, "overview.png": pngOver,
		}
		sums := map[string]string{}
		for n, b := range files {
			if err := os.WriteFile(filepath.Join(cdir, n), b, 0o644); err != nil {
				return nil, err
			}
			sums[n] = sum(b)
		}
		if err := os.WriteFile(filepath.Join(cdir, "manifest.yml"), []byte(Manifest(m, rep, sums)), 0o644); err != nil {
			return nil, err
		}
		prev = append(prev, render.Item{Number: m.Index, Band: string(m.Band), Image: pv})
		over = append(over, render.Item{Number: m.Index, Band: string(m.Band), Image: ov})
		res = append(res, Result{Meta: m, Report: rep, Dir: cdir})
	}
	sheet, _ := render.PNG(render.Sheet(prev, 6, 320, 240))
	if err := os.WriteFile(filepath.Join(dir, "contact-sheet.png"), sheet, 0o644); err != nil {
		return nil, err
	}
	strip, _ := render.PNG(render.Sheet(over, 2, 720, 81))
	if err := os.WriteFile(filepath.Join(dir, "overview-sheet.png"), strip, 0o644); err != nil {
		return nil, err
	}
	return res, os.WriteFile(filepath.Join(dir, "index.html"), []byte(Index(res)), 0o644)
}

// Index renders a static HTML overview of the set.
func Index(res []Result) string {
	var sb strings.Builder
	sb.WriteString(`<!doctype html><meta charset="utf-8"><title>OpenPak starter courses (unverified)</title>
<style>body{font:15px system-ui;margin:2rem auto;max-width:70rem;padding:0 1rem}table{border-collapse:collapse;width:100%}
td,th{border-bottom:1px solid #8884;padding:.4rem;text-align:left;vertical-align:top}img{width:240px;height:auto}
.easy{color:#2a8}.normal{color:#b80}.expert{color:#c33}</style>
<h1>OpenPak starter courses</h1>
<p>Generated, valid by static checks, <b>not yet loaded in the game</b>. See PLAYTEST.md. <a href="contact-sheet.png">Contact sheet</a>, <a href="overview-sheet.png">overview strips</a>.</p>
<table><tr><th>#</th><th>Preview</th><th>Course</th><th>Details</th></tr>`)
	for _, r := range res {
		m := r.Meta
		fmt.Fprintf(&sb, `<tr><td>%d</td><td><a href="%s/overview.png"><img src="%s/preview.png" alt=""></a></td><td><b>%s</b><br><span class="%s">%s</span> / %s / %s</td><td>%s<br><small>%s</small></td></tr>`+"\n",
			m.Index, html.EscapeString(m.Slug), html.EscapeString(m.Slug), html.EscapeString(m.Name), m.Band, m.Band,
			styleLabel(m.Style), m.Theme, html.EscapeString(m.Description), html.EscapeString(strings.Join(m.Templates, ", ")))
	}
	sb.WriteString("</table>\n")
	return sb.String()
}
